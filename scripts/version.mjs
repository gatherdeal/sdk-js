import { readFileSync, writeFileSync } from "node:fs";

const { version } = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const file = new URL("../src/version.ts", import.meta.url);
const source = `// Generated by scripts/version.mjs from package.json.\nexport const VERSION = ${JSON.stringify(version)};\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(file, "utf8") !== source) {
    console.error("src/version.ts is out of date. Run node scripts/version.mjs.");
    process.exitCode = 1;
  }
} else {
  writeFileSync(file, source);
}
